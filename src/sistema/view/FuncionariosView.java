    private void configurarTabela() {
        jTableFuncionarios.setModel(new DefaultTableModel(new Object[][] {},
                new String[] {"Nome", "Data de Admissão", "Salário (R$)", "Status"}) {
                    
            @Override
            public Class<?> getColumnClass(int coluna) {
                return coluna == 3 ? Boolean.class : String.class; // coluna Status = caixa de seleção
            }

            @Override
            public boolean isCellEditable(int linha, int coluna) {
                return false;
            }
        });
        
         // Cabeçalho
        jTableFuncionarios.getTableHeader().setFont(new Font("Segoe UI", Font.BOLD, 13));
        jTableFuncionarios.getTableHeader().setPreferredSize(new Dimension(0, 36));
        jTableFuncionarios.getTableHeader().setReorderingAllowed(false);

        
        jTableFuncionarios.setRowHeight(36);
        jTableFuncionarios.setShowVerticalLines(false);
        jTableFuncionarios.setShowHorizontalLines(true);
        jTableFuncionarios.setIntercellSpacing(new java.awt.Dimension(0, 1));
        jTableFuncionarios.setGridColor(new Color(0xE3EAF5));
        jTableFuncionarios.setBackground(Color.WHITE);
        jTableFuncionarios.setSelectionBackground(new Color(0xD6E4FA));
        jTableFuncionarios.setSelectionForeground(new Color(0x0F1B33));
        jTableFuncionarios.setSelectionMode(ListSelectionModel.SINGLE_SELECTION);
        jTableFuncionarios.setFillsViewportHeight(true);
 
    }

    
